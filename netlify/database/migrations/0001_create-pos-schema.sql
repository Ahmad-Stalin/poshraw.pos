CREATE TABLE users (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  username TEXT NOT NULL,
  email TEXT,
  role TEXT NOT NULL CHECK (role IN ('owner', 'cashier', 'stock_manager')),
  password_salt TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  active INTEGER NOT NULL DEFAULT 1 CHECK (active IN (0, 1)),
  created_at TEXT NOT NULL
);
CREATE UNIQUE INDEX users_username_unique ON users (LOWER(username));

CREATE TABLE sessions (
  token_hash TEXT PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at BIGINT NOT NULL,
  created_at TEXT NOT NULL
);
CREATE INDEX sessions_expiry ON sessions(expires_at);

CREATE TABLE login_attempts (
  ip TEXT PRIMARY KEY,
  count INTEGER NOT NULL DEFAULT 0,
  reset_at BIGINT NOT NULL
);

CREATE TABLE categories (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  created_at TEXT NOT NULL
);
CREATE UNIQUE INDEX categories_name_unique ON categories (LOWER(name));

CREATE TABLE customers (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  phone TEXT NOT NULL DEFAULT '',
  notes TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL
);
CREATE UNIQUE INDEX customers_phone_unique ON customers(phone) WHERE phone <> '';

CREATE TABLE suppliers (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  phone TEXT NOT NULL DEFAULT '',
  notes TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL
);
CREATE UNIQUE INDEX suppliers_phone_unique ON suppliers(phone) WHERE phone <> '';

CREATE TABLE products (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  category_id TEXT NOT NULL REFERENCES categories(id),
  barcode TEXT NOT NULL DEFAULT '',
  purchase_price BIGINT NOT NULL CHECK (purchase_price >= 0),
  sale_price BIGINT NOT NULL CHECK (sale_price >= 0),
  quantity BIGINT NOT NULL CHECK (quantity >= 0),
  minimum_stock BIGINT NOT NULL CHECK (minimum_stock >= 0),
  unit TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'draft', 'archived')),
  description TEXT NOT NULL DEFAULT '',
  image_url TEXT NOT NULL DEFAULT ''
);
CREATE UNIQUE INDEX products_barcode_unique ON products(barcode) WHERE barcode <> '';
CREATE INDEX products_name ON products(name);

CREATE TABLE product_images (
  id TEXT PRIMARY KEY,
  product_id TEXT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  url TEXT NOT NULL,
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL
);
CREATE INDEX product_images_product ON product_images(product_id, sort_order);

CREATE TABLE product_colors (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  hex TEXT NOT NULL,
  created_at TEXT NOT NULL
);

CREATE TABLE product_sizes (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL
);

CREATE TABLE product_variants (
  id TEXT PRIMARY KEY,
  product_id TEXT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  color_id TEXT REFERENCES product_colors(id) ON DELETE SET NULL,
  size_id TEXT REFERENCES product_sizes(id) ON DELETE SET NULL,
  sku TEXT NOT NULL DEFAULT '',
  quantity BIGINT NOT NULL DEFAULT 0,
  price_adjustment BIGINT NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL
);
CREATE INDEX product_variants_product ON product_variants(product_id);

CREATE TABLE size_guides (
  id TEXT PRIMARY KEY,
  category TEXT NOT NULL,
  label TEXT NOT NULL,
  measurements TEXT NOT NULL,
  created_at TEXT NOT NULL
);
CREATE INDEX size_guides_category ON size_guides(category);

CREATE TABLE purchase_orders (
  id TEXT PRIMARY KEY,
  order_number TEXT NOT NULL UNIQUE,
  supplier_id TEXT NOT NULL REFERENCES suppliers(id),
  status TEXT NOT NULL CHECK (status IN ('ordered', 'received', 'cancelled')),
  subtotal_amount BIGINT NOT NULL CHECK (subtotal_amount >= 0),
  notes TEXT NOT NULL DEFAULT '',
  created_by TEXT NOT NULL REFERENCES users(id),
  created_at TEXT NOT NULL,
  received_at TEXT
);
CREATE INDEX purchase_orders_created ON purchase_orders(created_at DESC);

CREATE TABLE purchase_items (
  seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id TEXT PRIMARY KEY,
  purchase_id TEXT NOT NULL REFERENCES purchase_orders(id) ON DELETE CASCADE,
  product_id TEXT REFERENCES products(id) ON DELETE SET NULL,
  product_name TEXT NOT NULL,
  quantity BIGINT NOT NULL CHECK (quantity > 0),
  unit_cost BIGINT NOT NULL CHECK (unit_cost >= 0)
);
CREATE INDEX purchase_items_purchase ON purchase_items(purchase_id, seq);

CREATE TABLE supplier_payments (
  id TEXT PRIMARY KEY,
  supplier_id TEXT NOT NULL REFERENCES suppliers(id),
  purchase_id TEXT REFERENCES purchase_orders(id) ON DELETE SET NULL,
  amount BIGINT NOT NULL CHECK (amount > 0),
  payment_method TEXT NOT NULL CHECK (payment_method IN ('cash', 'electronic')),
  note TEXT NOT NULL DEFAULT '',
  user_id TEXT NOT NULL REFERENCES users(id),
  created_at TEXT NOT NULL
);
CREATE INDEX supplier_payments_supplier ON supplier_payments(supplier_id, created_at DESC);

CREATE TABLE stock_adjustments (
  id TEXT PRIMARY KEY,
  product_id TEXT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  product_name TEXT NOT NULL,
  amount BIGINT NOT NULL CHECK (amount <> 0),
  reason TEXT NOT NULL,
  created_at TEXT NOT NULL
);
CREATE INDEX stock_adjustments_created ON stock_adjustments(created_at DESC);

CREATE TABLE sales (
  id TEXT PRIMARY KEY,
  receipt_number TEXT NOT NULL UNIQUE,
  user_id TEXT NOT NULL REFERENCES users(id),
  customer_id TEXT REFERENCES customers(id) ON DELETE SET NULL,
  subtotal_amount BIGINT NOT NULL DEFAULT 0 CHECK (subtotal_amount >= 0),
  tax_rate_bps INTEGER NOT NULL DEFAULT 0 CHECK (tax_rate_bps BETWEEN 0 AND 10000),
  tax_name TEXT NOT NULL DEFAULT 'باژ',
  tax_amount BIGINT NOT NULL DEFAULT 0 CHECK (tax_amount >= 0),
  total_amount BIGINT NOT NULL CHECK (total_amount >= 0),
  total_cost BIGINT NOT NULL CHECK (total_cost >= 0),
  amount_paid BIGINT NOT NULL DEFAULT 0 CHECK (amount_paid >= 0),
  customer_name TEXT NOT NULL DEFAULT '',
  is_export INTEGER NOT NULL DEFAULT 0 CHECK (is_export IN (0, 1)),
  currency_code TEXT NOT NULL DEFAULT 'IQD',
  exchange_rate DOUBLE PRECISION NOT NULL DEFAULT 1.0,
  shipping_cost BIGINT NOT NULL DEFAULT 0 CHECK (shipping_cost >= 0),
  customs_charges BIGINT NOT NULL DEFAULT 0 CHECK (customs_charges >= 0),
  destination_country TEXT,
  is_credit INTEGER NOT NULL DEFAULT 0 CHECK (is_credit IN (0, 1)),
  payment_method TEXT NOT NULL DEFAULT 'cash' CHECK (payment_method IN ('cash', 'electronic')),
  created_at TEXT NOT NULL
);
CREATE INDEX sales_created ON sales(created_at DESC);
CREATE INDEX sales_customer ON sales(customer_id);

CREATE TABLE sale_items (
  seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id TEXT PRIMARY KEY,
  sale_id TEXT NOT NULL REFERENCES sales(id) ON DELETE CASCADE,
  product_id TEXT REFERENCES products(id) ON DELETE SET NULL,
  product_name TEXT NOT NULL,
  quantity BIGINT NOT NULL CHECK (quantity > 0),
  sale_price BIGINT NOT NULL CHECK (sale_price >= 0),
  purchase_price BIGINT NOT NULL CHECK (purchase_price >= 0)
);
CREATE INDEX sale_items_sale ON sale_items(sale_id, seq);

CREATE TABLE sales_returns (
  id TEXT PRIMARY KEY,
  return_number TEXT NOT NULL UNIQUE,
  sale_id TEXT NOT NULL REFERENCES sales(id),
  subtotal_amount BIGINT NOT NULL CHECK (subtotal_amount >= 0),
  cost_amount BIGINT NOT NULL CHECK (cost_amount >= 0),
  tax_amount BIGINT NOT NULL CHECK (tax_amount >= 0),
  total_amount BIGINT NOT NULL CHECK (total_amount >= 0),
  refund_method TEXT NOT NULL CHECK (refund_method IN ('cash', 'electronic', 'credit')),
  reason TEXT NOT NULL,
  user_id TEXT NOT NULL REFERENCES users(id),
  created_at TEXT NOT NULL
);
CREATE INDEX sales_returns_sale ON sales_returns(sale_id, created_at DESC);

CREATE TABLE return_items (
  id TEXT PRIMARY KEY,
  return_id TEXT NOT NULL REFERENCES sales_returns(id) ON DELETE CASCADE,
  sale_item_id TEXT NOT NULL REFERENCES sale_items(id),
  product_id TEXT REFERENCES products(id) ON DELETE SET NULL,
  product_name TEXT NOT NULL,
  quantity BIGINT NOT NULL CHECK (quantity > 0),
  unit_sale_price BIGINT NOT NULL CHECK (unit_sale_price >= 0),
  unit_cost BIGINT NOT NULL CHECK (unit_cost >= 0)
);
CREATE INDEX return_items_sale_item ON return_items(sale_item_id);
CREATE INDEX return_items_return ON return_items(return_id);

CREATE TABLE customer_payments (
  id TEXT PRIMARY KEY,
  customer_id TEXT NOT NULL REFERENCES customers(id),
  amount BIGINT NOT NULL CHECK (amount > 0),
  payment_method TEXT NOT NULL CHECK (payment_method IN ('cash', 'electronic')),
  note TEXT NOT NULL DEFAULT '',
  user_id TEXT NOT NULL REFERENCES users(id),
  created_at TEXT NOT NULL
);
CREATE INDEX customer_payments_customer ON customer_payments(customer_id, created_at DESC);

CREATE TABLE loyalty_settings (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  amount_per_point BIGINT NOT NULL DEFAULT 0 CHECK (amount_per_point >= 0),
  updated_at TEXT NOT NULL
);

CREATE TABLE loyalty_ledger (
  id TEXT PRIMARY KEY,
  customer_id TEXT NOT NULL REFERENCES customers(id),
  sale_id TEXT REFERENCES sales(id) ON DELETE SET NULL,
  return_id TEXT REFERENCES sales_returns(id) ON DELETE SET NULL,
  points BIGINT NOT NULL CHECK (points <> 0),
  source TEXT NOT NULL CHECK (source IN ('sale', 'return', 'adjustment')),
  note TEXT NOT NULL,
  user_id TEXT REFERENCES users(id) ON DELETE SET NULL,
  created_at TEXT NOT NULL
);
CREATE INDEX loyalty_ledger_customer ON loyalty_ledger(customer_id, created_at DESC);

CREATE TABLE price_changes (
  id TEXT PRIMARY KEY,
  product_id TEXT REFERENCES products(id) ON DELETE SET NULL,
  product_name TEXT NOT NULL,
  old_purchase_price BIGINT NOT NULL,
  new_purchase_price BIGINT NOT NULL,
  old_sale_price BIGINT NOT NULL,
  new_sale_price BIGINT NOT NULL,
  user_id TEXT REFERENCES users(id) ON DELETE SET NULL,
  created_at TEXT NOT NULL
);
CREATE INDEX price_changes_created ON price_changes(created_at DESC);

CREATE TABLE accounting_settings (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  tax_rate_bps INTEGER NOT NULL DEFAULT 0 CHECK (tax_rate_bps BETWEEN 0 AND 10000),
  tax_name TEXT NOT NULL DEFAULT 'باژ',
  updated_at TEXT NOT NULL
);

CREATE TABLE expense_categories (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  color TEXT NOT NULL DEFAULT '#4b9061',
  created_at TEXT NOT NULL
);

CREATE TABLE expenses (
  id TEXT PRIMARY KEY,
  title TEXT NOT NULL,
  category TEXT NOT NULL,
  amount BIGINT NOT NULL CHECK (amount > 0),
  payment_method TEXT NOT NULL CHECK (payment_method IN ('cash', 'electronic')),
  note TEXT NOT NULL DEFAULT '',
  user_id TEXT NOT NULL REFERENCES users(id),
  created_at TEXT NOT NULL,
  voided INTEGER NOT NULL DEFAULT 0,
  voided_at TEXT,
  voided_by TEXT REFERENCES users(id)
);
CREATE INDEX expenses_created ON expenses(created_at DESC);

CREATE TABLE cash_ledger (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind TEXT NOT NULL CHECK (kind IN ('sale', 'expense', 'adjustment')),
  amount BIGINT NOT NULL CHECK (amount <> 0),
  sale_id TEXT REFERENCES sales(id) ON DELETE SET NULL,
  expense_id TEXT REFERENCES expenses(id) ON DELETE SET NULL,
  note TEXT NOT NULL,
  user_id TEXT NOT NULL REFERENCES users(id),
  created_at TEXT NOT NULL
);

CREATE TABLE cash_reconciliations (
  seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id TEXT PRIMARY KEY,
  ledger_through_id BIGINT NOT NULL,
  opening_balance BIGINT NOT NULL,
  expected_balance BIGINT NOT NULL,
  counted_balance BIGINT NOT NULL,
  variance BIGINT NOT NULL,
  note TEXT NOT NULL DEFAULT '',
  user_id TEXT NOT NULL REFERENCES users(id),
  created_at TEXT NOT NULL,
  voided INTEGER NOT NULL DEFAULT 0,
  voided_at TEXT,
  voided_by TEXT REFERENCES users(id)
);
CREATE INDEX cash_reconciliations_created ON cash_reconciliations(created_at DESC);

CREATE TABLE tax_payments (
  id TEXT PRIMARY KEY,
  amount BIGINT NOT NULL CHECK (amount > 0),
  payment_method TEXT NOT NULL CHECK (payment_method IN ('cash', 'electronic')),
  note TEXT NOT NULL DEFAULT '',
  user_id TEXT NOT NULL REFERENCES users(id),
  created_at TEXT NOT NULL,
  voided INTEGER NOT NULL DEFAULT 0,
  voided_at TEXT,
  voided_by TEXT REFERENCES users(id)
);
CREATE INDEX tax_payments_created ON tax_payments(created_at DESC);

